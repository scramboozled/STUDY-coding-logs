-- BUILT-IN FUNCTIONS


-- LOWER CASE, UPPER CASE OF LETTERS AND LENGTH OF STRING
SELECT LOWER(FIRST_NAME), LOWER(LAST_NAME),LOWER(EMAIL) FROM CUSTOMER WHERE LENGTH(FIRST_NAME) > 10 OR LENGTH(LAST_NAME) > 10;

-- LEFT/RIGHT FUNCTIONS
SELECT LEFT(EMAIL,5)|| '***' || RIGHT(EMAIL,4) AS ANON_EMAIL FROM CUSTOMER;

-- POSITION FUNCTIONS
SELECT LEFT(EMAIL, POSITION('.' IN EMAIL) - 1) AS FIRST_NAME FROM CUSTOMER;

-- SUBSTRING FUNCTION
-- from inside substring function is written in lower case for better readability
SELECT SUBSTRING(EMAIL,1,7) FROM CUSTOMER;
SELECT SUBSTRING(EMAIL from 1 FOR 7) FROM CUSTOMER;

-- EXTRACT FUNCTION
SELECT EXTRACT(MONTHS from PAYMENT_DATE), SUM(AMOUNT) as total_payment_amount FROM PAYMENT GROUP BY 1 ORDER BY 2 DESC;
SELECT EXTRACT(WEEK from PAYMENT_DATE),CUSTOMER_ID, SUM(AMOUNT) as total_payment_amount FROM PAYMENT GROUP BY 1,2 ORDER BY 3 DESC;

-- TO_CHAR FUNCTION
SELECT TO_CHAR(PAYMENT_DATE, 'Mon-yyyy') , SUM(AMOUNT) as total_payment_amount FROM PAYMENT GROUP BY 1 ORDER BY 2 DESC;


-- CURRENT_DATE and CURRENT_TIMESTAMP
SELECT CURRENT_DATE, EXTRACT(DAY FROM CURRENT_TIMESTAMP - PAYMENT_DATE) + EXTRACT(HOUR FROM CURRENT_TIMESTAMP - PAYMENT_DATE) || ' HOURS' AS CURRENT_INTERVAL_TIME FROM PAYMENT;

-- Mathematical Functions
SELECT 2*2, 2-5, 4/3, 4.0/3, 2^3, 2%4;

SELECT ABS(-3), CEILING(4.333), FLOOR(4.333), ROUND(4.339, 2);




