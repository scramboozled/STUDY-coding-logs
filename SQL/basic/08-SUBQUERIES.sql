-- Subqueries


-- SUBQUERY IN WHERE
SELECT * FROM
PAYMENT
WHERE AMOUNT > (SELECT AVG(AMOUNT) FROM PAYMENT);

SELECT * FROM PAYMENT
WHERE CUSTOMER_ID IN (SELECT CUSTOMER_ID FROM CUSTOMER WHERE FIRST_NAME LIKE 'A%');

--SUBQUERY IN FROM 
SELECT AVG(TOTAL_AMOUNT) FROM
(SELECT CUSTOMER_ID, SUM(AMOUNT) AS TOTAL_AMOUNT FROM PAYMENT GROUP BY 1);


-- SUBQUERY IN SELECT
SELECT 
*, (SELECT AVG(AMOUNT) FROM PAYMENT)
FROM PAYMENT;

-- CORRELATED SUBQUERY -> subquery that get data from main query to return result
SELECT
* 
FROM 
PAYMENT A
WHERE AMOUNT = (SELECT MAX(AMOUNT) FROM PAYMENT B WHERE A.CUSTOMER_ID = B.CUSTOMER_ID)
ORDER BY CUSTOMER_ID;