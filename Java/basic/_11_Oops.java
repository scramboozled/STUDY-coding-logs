// encapsulation: Bundling data (attributes) and methods (functions) that operate on the data into a single unit or class. 
        // usage of access modifiers (private, public, protected) to restrict direct access to some of the object's components.
        //  public: accessible from any other class
        //  private: accessible only within the defined class
        //  protected: accessible within the same package and subclasses
    // abstraction: Hiding complex implementation details and showing only the essential features of the object.    
        // achieved using abstract classes and interfaces
        // interface: A contract that defines a set of methods that implementing classes must provide
        // abstract class: A class that cannot be instantiated on its own and may contain abstract methods (methods without a body) that must be implemented by subclasses
    // inheritance: Mechanism where one class can inherit properties and behaviors (methods) from another
        // promotes code reusability and establishes a hierarchical relationship between classes
        // single inheritance: A class inherits from one superclass
        // multilevel inheritance: A class inherits from a superclass, which in turn inherits from another superclass
        // hierarchical inheritance: Multiple classes inherit from a single superclass
    // polymorphism: Ability of a single function or method to operate in different ways based on the object it is acting upon.
        // compile-time polymorphism (method overloading): Multiple methods with the same name but different parameter lists within the same class
        // run-time polymorphism (method overriding): A subclass provides a specific implementation of a method that is already defined in its superclass
